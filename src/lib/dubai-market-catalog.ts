export function normalizeMarketName(value: string) {
  return value.trim().replace(/\s+/g, " ");
}

export function marketNameKey(value: string) {
  return normalizeMarketName(value).toLocaleLowerCase("en");
}

export function uniqueMarketNames(values: Array<string | null | undefined>) {
  const seen = new Set<string>();
  return values
    .map((value) => normalizeMarketName(value ?? ""))
    .filter((value) => {
      if (!value) return false;
      const key = marketNameKey(value);
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    })
    .sort((a, b) => a.localeCompare(b, "en"));
}
